_DRAFT_VALUE_RE = re.compile(
    r"depths?\s+corrected\s+for\s+([\d.]+)\s*meter\s*ship\s*draft", re.IGNORECASE,
)
_DRAUGHT_RE = re.compile(
    r"bathymetry\s+corrected\s+for\s+draught", re.IGNORECASE,
)


def _matthews_zone(code: int) -> str:
    return f"Matthews' zone {code:02d}" if 1 <= code <= 55 else ""


def _bat_cpco_label(code_text: str) -> str:
    if not code_text:
        return "unspecified"
    code_text = code_text.strip()
    if code_text in BAT_CPCO_LABELS:
        return BAT_CPCO_LABELS[code_text]
    try:
        code = int(code_text)
    except ValueError:
        return f"non-numeric code {code_text!r}"
    zone = _matthews_zone(code)
    if zone:
        return zone
    return f"code {code_text} outside documented BAT_CPCO table"


def _vdatum_label(code_text: str) -> str:
    if not code_text:
        return "unspecified"
    code_text = code_text.strip()
    return VDATUM_CO_LABELS.get(code_text, f"code {code_text} outside documented VDATUM_CO table")


def _g_formu_label(code_text: str) -> str:
    if not code_text:
        return "unspecified"
    code_text = code_text.strip()
    return G_FORMU_CO_LABELS.get(code_text, f"code {code_text} outside documented G_FORMU_CO table")


def _g_rfsys_label(code_text: str) -> str:
    if not code_text:
        return "unspecified"
    code_text = code_text.strip()
    return G_RFSYS_CO_LABELS.get(code_text, f"code {code_text} outside documented G_RFSYS_CO table")


