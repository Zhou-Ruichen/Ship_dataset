"""Source physical-correction states for the delivered ship products.

This module structures what the delivered sources state about applied
physical corrections — sound speed, attitude, draft, tide, vertical datum
and gravity formula/reference system — without changing any depth or FAA
value. Every state names its evidence carrier (formal header field, source
processing comment, or auxiliary record) and its scope (one file, one
cruise, one header). Where a source is silent, the state is `unknown`,
never "uncorrected".

Covered inputs (read-only):

1. `trackline/source_headers.parquet` — 695 static MGD77T formal headers.
2. `legacy_faa/source_metadata/*.h77t` + `conversion_manifest.csv` — 15
   legacy FAA surveys whose headers live outside the static tree.
3. `legacy_faa_additional/` — six additional FAA surveys; their headers
   are the same static-tree files already counted in (1), so they link to
   one static header each instead of adding a second source.
4. Swath: the six-cruise extraction manifests (1508 files). For every
   `.mb41.gz` file the gzip preamble before the first `SB2100DR` record
   carries the provider's `SB2100TR` mbprocess comments; each file also
   has an `.inf` generated by the archive, whose metadata lines and
   record-type notices (SVP/SSV/attitude) are captured verbatim with line
   numbers. `.mb58/.mb84/.rc00` files carry no per-file processing
   comments in their delivered form; their `.inf` record-type notices are
   retained the same way.
5. One HNRO14RR sample file retained as evidence for the existing source
   depth/beam-anomaly sensitivity record; HNRO14RR is not part of the
   six-cruise product and contributes no new numeric product.

Outputs (under `ncei/derived/processing_revision_20261025/source_corrections/`):

- `trackline_source_corrections.parquet/.csv`  — 695 rows, one per static
  source, header-declared states (sound speed, vertical datum, draft,
  tide, attitude, gravity) plus per-record code summaries.
- `legacy_faa_source_corrections.parquet/.csv` — 21 rows (15 + 6), with
  the six additional surveys joined to their static-header rows.
- `swath_source_corrections.parquet/.csv`      — 1508 rows plus the one
  HNRO14RR sample-evidence row, one per delivered swath source file.
- `swath_svp_profiles.parquet`                 — distinct sound-speed
  profiles quoted in the mbprocess preambles, keyed for the file table.
- `evidence_texts.parquet`                     — verbatim source texts with
  file/line/byte pointers.
- `summary.csv`, `checks.json`, `README.md`.

Run from the repository root:

    python -m ncei.trackline source-corrections \
        --product-root ncei/derived/processing_revision_20261025 \
        [--raw-root ncei/raw_round2/platforms_tree]
"""

