@dataclass
class MB41Preamble:
    relpath: str
    header_bytes: int
    fields: dict[str, str]
    svp: list[tuple[float, float]]


def read_mb41_preamble(path: Path, relpath: str, max_read: int = 65536) -> MB41Preamble | None:
    """Decompress only the beginning of an .mb41.gz up to the first data
    record; the provider's processing comments sit before it."""
    with gzip.open(path, "rb") as handle:
        data = handle.read(max_read)
    idx = data.find(b"SB2100DR")
    head = data[: idx if idx >= 0 else len(data)].decode("latin1")
    lines = [l for l in head.replace("\r\n", "\n").split("\n") if l != "SB2100TR"]
    fields: dict[str, str] = {}
    for line in lines:
        stripped = line.strip()
        for prefix in ("METASVCORRECTED:", "METATIDECORRECTED:", "METAROLLBIAS:",
                       "METAPITCHBIAS:", "METAHEADINGBIAS:", "METADRAFT:"):
            if stripped.startswith(prefix):
                fields[prefix[:-1]] = stripped[len(prefix):].strip()
    # Full processing-mode statement: from the "Depths and crosstrack
    # distances ..." line through its continuation lines, stopping at the
    # "Control Parameters:" section header.
    for index, line in enumerate(lines):
        stripped = line.strip()
        if stripped.startswith("Depths and crosstrack distances"):
            parts = [stripped]
            j = index + 1
            while j < len(lines) and not lines[j].strip().startswith("Control Parameters"):
                parts.append(lines[j].strip())
                j += 1
            fields["mode_statement"] = " ".join(parts)
            break
    def find(prefix: str) -> str | None:
        for line in lines:
            if line.strip().startswith(prefix):
                return line.strip()
        return None
    for key, prefix in (
        ("mbprocess_version", "MB-system Version"),
        ("mbprocess_run_by", "Run by user"),
        ("raytrace_statement", "Depths and crosstrack distances recalculated"),
        ("output_reference", "Output bathymetry reference"),
        ("roll_bias_step", "Roll bias:"),
        ("pitch_bias_step", "Pitch bias:"),
        ("draft_step", "Draft set:"),
        ("heave_step", "Heave:"),
        ("tide_step", "Tide calculation"),
        ("default_ssv", "Default SSV"),
        ("svp_file", "SVP file:"),
    ):
        value = find(prefix)
        if value is not None:
            fields[key] = value
    svp = []
    for line in lines:
        m = re.match(r"^\s*(\d+\.\d+)\s+(\d+\.\d+)\s*$", line)
        if m:
            svp.append((float(m.group(1)), float(m.group(2))))
    return MB41Preamble(relpath, idx if idx >= 0 else len(data), fields, svp)


_INF_META_KEYS = (
    ("corrected_depths", "Corrected Depths:"),
    ("tide_corrected", "Tide Corrected:"),
    ("roll_bias", "Roll Bias:"),
    ("pitch_bias", "Pitch Bias:"),
    ("heading_bias", "Heading Bias:"),
    ("draft", "Draft:"),
    ("depths_manually_edited", "Depths Manually Edited:"),
    ("depths_auto_edited", "Depths Auto-Edited:"),
    ("sonar", "Sonar:"),
    ("vessel", "Vessel:"),
    ("institution", "Institution:"),
)


def read_inf(path: Path, relpath: str) -> dict:
    """Read one archive .inf: metadata lines and SVP/SSV/attitude
    record-type notices, verbatim with their line numbers."""
    out: dict = {"path": relpath}
    try:
        lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return out
    for number, line in enumerate(lines, 1):
        for key, prefix in _INF_META_KEYS:
            if line.startswith(prefix) and key not in out:
                out[key] = line[len(prefix):].strip()
                out[key + "_verbatim"] = line
                out[key + "_line"] = number
        if "MB_DATA_VELOCITY_PROFILE" in line and "svp_notice" not in out:
            out["svp_notice"], out["svp_notice_line"] = line, number
        if "MB_DATA_SSV" in line and "ssv_notice" not in out:
            out["ssv_notice"], out["ssv_notice_line"] = line, number
        if re.search(r"MB_DATA_ATTITUDE\d*\b", line):
            out.setdefault("attitude_notices", []).append((line, number))
    return out


def _inf_path(raw_root: Path, relpath: str) -> Path | None:
    base = raw_root / relpath
    stem = str(base)[:-3] if str(base).endswith(".gz") else str(base)
    candidates = [Path(stem + ".inf"),
                  base.parent / "generated" / (Path(stem).name + ".inf")]
    for candidate in candidates:
        if candidate.is_file():
            return candidate
    return None


def _inf_columns(inf: dict) -> dict:
    attitude = inf.get("attitude_notices") or []
    return {
        "inf_path": inf.get("path"),
        "inf_svp_notice": inf.get("svp_notice"),
        "inf_svp_notice_line": inf.get("svp_notice_line"),
        "inf_ssv_notice": inf.get("ssv_notice"),
        "inf_ssv_notice_line": inf.get("ssv_notice_line"),
        "inf_attitude_notice": " | ".join(text for text, _ in attitude) or None,
        "inf_attitude_notice_first_line": attitude[0][1] if attitude else None,
    }


def _inf_evidence_rows(scope: str, inf: dict) -> list[dict]:
    rows = []
    for key, _ in _INF_META_KEYS[:8]:
        if key in inf:
            rows.append({
                "scope": scope, "carrier": "inf_file",
                "location": f"{inf['path']}:line {inf[key + '_line']}",
                "text": inf[key + "_verbatim"],
            })
    for key in ("svp_notice", "ssv_notice"):
        if key in inf:
            rows.append({
                "scope": scope, "carrier": "inf_file",
                "location": f"{inf['path']}:line {inf[key + '_line']}",
                "text": inf[key],
            })
    for text, number in inf.get("attitude_notices", []):
        rows.append({
            "scope": scope, "carrier": "inf_file",
            "location": f"{inf['path']}:line {number}",
            "text": text,
        })
    return rows


RAYTRACE_STATE = "applied_preamble_raytracing"
DEPTH_ADJUST_STATE = "declared_corrected_transducer_depth_heave_adjustment_mode"


def _mb41_row(relpath: str, filekey: str, cruise: str, preamble: MB41Preamble | None,
              inf: dict) -> tuple[dict, list[dict], list[tuple[float, float]] | None]:
    fields = preamble.fields if preamble else {}
    raytrace = fields.get("raytrace_statement")
    has_inf = bool(inf)

    if raytrace:
        ss_state = RAYTRACE_STATE
        ss_scope = "this file's mbprocess preamble"
    elif fields.get("METASVCORRECTED") == "1":
        # The recorded step adjusted depths for transducer depth and/or
        # heave; it did not redo raytracing. METASVCORRECTED stays a
        # declaration of the file, not of this step.
        ss_state = DEPTH_ADJUST_STATE
        ss_scope = "this file's mbprocess preamble"
    elif has_inf and "svp_notice" in inf:
        ss_state = "svp_records_present_application_unknown"
        ss_scope = "this file's .inf record-type notices"
    else:
        ss_state = "unknown"
        ss_scope = "no readable processing declaration"

    roll_step = fields.get("roll_bias_step", "")
    pitch_step = fields.get("pitch_bias_step", "")
    if "OFF" in roll_step and "OFF" in pitch_step:
        att_step = "bias_reapplication_off_in_this_step"
    elif roll_step or pitch_step:
        att_step = "declared:" + ";".join(x for x in (roll_step, pitch_step) if x)
    else:
        att_step = "unknown"
    meta_roll = fields.get("METAROLLBIAS")
    meta_pitch = fields.get("METAPITCHBIAS")

    tide_step = fields.get("tide_step", "")
    meta_tide = fields.get("METATIDECORRECTED")
    if tide_step:
        tide_state = ("not_applied_in_this_step" if "off" in tide_step.lower()
                      else f"declared:{tide_step}")
    elif meta_tide is not None:
        tide_state = f"metadata_flag:{meta_tide}"
    else:
        tide_state = "unknown"

    svp = preamble.svp if (preamble and preamble.svp) else None
    row = {
        "cruise": cruise,
        "filekey": filekey,
        "source_relpath": relpath,
        "mb_format": 41,
        "sound_speed_correction_state": ss_state,
        "sound_speed_correction_scope": ss_scope,
        "mbprocess_mode_statement": fields.get("mode_statement"),
        "svp_n_points": len(svp) if svp else 0,
        "svp_shallowest_depth_m": svp[0][0] if svp else None,
        "svp_deepest_depth_m": svp[-1][0] if svp else None,
        "svp_velocity_range_m_s": (
            f"{min(v for _, v in svp):.2f}-{max(v for _, v in svp):.2f}" if svp else None
        ),
        "attitude_bias_metadata": (
            f"roll={meta_roll};pitch={meta_pitch}" if meta_roll is not None or meta_pitch is not None else None
        ),
        "attitude_bias_step_state": att_step,
        "heave_step_state": fields.get("heave_step") or "unknown",
        "draft_metadata_m": fields.get("METADRAFT"),
        "draft_step": fields.get("draft_step"),
        "tide_state": tide_state,
        "tide_scope": "this file's mbprocess preamble" if tide_step else "no readable declaration",
        "depth_output_reference": fields.get("output_reference"),
        "vertical_datum_state": "unknown",
        "vertical_datum_note": "CORRECTED is not a named vertical datum",
        "mbprocess_version": fields.get("mbprocess_version"),
        "mbprocess_run_by": fields.get("mbprocess_run_by"),
        "preamble_bytes": preamble.header_bytes if preamble else None,
        "inf_file_present": has_inf,
        "inf_corrected_depths": inf.get("corrected_depths"),
        "inf_tide_corrected": inf.get("tide_corrected"),
        "inf_roll_bias": inf.get("roll_bias"),
        "inf_pitch_bias": inf.get("pitch_bias"),
        "inf_draft": inf.get("draft"),
    }
    row.update(_inf_columns(inf))
    texts = []
    for key in ("mode_statement", "output_reference", "roll_bias_step",
                "pitch_bias_step", "draft_step", "heave_step", "tide_step",
                "mbprocess_version", "mbprocess_run_by", "default_ssv",
                "svp_file"):
        value = fields.get(key)
        if value:
            texts.append(value)
    for key in ("METASVCORRECTED", "METATIDECORRECTED", "METAROLLBIAS",
                "METAPITCHBIAS", "METAHEADINGBIAS", "METADRAFT"):
        if key in fields:
            texts.append(f"{key}:{fields[key]}")
    return row, texts, svp


def _binary_row(cruise: str, filekey: str, relpath: str, mb_format: int,
                inf: dict) -> tuple[dict, list[dict]]:
    has_inf = bool(inf)
    if has_inf and "svp_notice" in inf:
        ss_state = "svp_records_present_application_unknown"
        ss_scope = "this file's .inf record-type notices"
    else:
        ss_state = "unknown"
        ss_scope = "no readable processing declaration in delivered file or .inf"
    row = {
        "cruise": cruise,
        "filekey": filekey,
        "source_relpath": relpath,
        "mb_format": mb_format,
        "sound_speed_correction_state": ss_state,
        "sound_speed_correction_scope": ss_scope,
        "mbprocess_mode_statement": None,
        "svp_n_points": None,
        "svp_shallowest_depth_m": None,
        "svp_deepest_depth_m": None,
        "svp_velocity_range_m_s": None,
        "attitude_bias_metadata": None,
        "attitude_bias_step_state": (
            "attitude_records_present_application_unknown"
            if has_inf and "attitude_notices" in inf else "unknown"
        ),
        "heave_step_state": "unknown",
        "draft_metadata_m": None,
        "draft_step": None,
        "tide_state": "unknown",
        "tide_scope": "no readable declaration",
        "depth_output_reference": inf.get("corrected_depths") if has_inf else None,
        "vertical_datum_state": "unknown",
        "vertical_datum_note": (
            "no delivered datum declaration"
            if not (has_inf and inf.get("corrected_depths"))
            else "CORRECTED is not a named vertical datum"
        ),
        "mbprocess_version": None,
        "mbprocess_run_by": None,
        "preamble_bytes": None,
        "inf_file_present": has_inf,
        "inf_corrected_depths": inf.get("corrected_depths"),
        "inf_tide_corrected": inf.get("tide_corrected"),
        "inf_roll_bias": inf.get("roll_bias"),
        "inf_pitch_bias": inf.get("pitch_bias"),
        "inf_draft": inf.get("draft"),
    }
    row.update(_inf_columns(inf))
    return row, []


SWATH_BATCHES = (
    ("first_batch", ("HNRO07RR", "NT05-06")),
    ("navigation_affected_extension", ("AII8L18", "HNRO05RR", "HNRO06RR", "RR1412")),
)

HNRO14RR_SAMPLE = (
    "roger_revelle/HNRO14RR/20070726161003120_sb2100_vf.20000203-2400p.mb41.gz"
)


def build_swath_tables(product_root: Path, raw_root: Path) -> tuple[pl.DataFrame, pl.DataFrame, pl.DataFrame]:
    """One row per delivered swath source file (1508) plus the HNRO14RR
    sample row, distinct SVP profiles, and verbatim evidence texts."""
    rows, evidence, svp_profiles = [], [], []
    svp_seen: dict[tuple[tuple[float, float], ...], int] = {}

    def register_svp(cruise: str, svp: list[tuple[float, float]] | None) -> int | None:
        if svp is None:
            return None
        key = tuple(svp)
        if key not in svp_seen:
            svp_seen[key] = len(svp_profiles)
            svp_profiles.append({
                "svp_id": len(svp_profiles),
                "cruise": cruise,
                "n_points": len(svp),
                "profile_text": "\n".join(f"{d:.2f} {v:.2f}" for d, v in svp),
            })
        return svp_seen[key]

    for batch, cruises in SWATH_BATCHES:
        for cruise in cruises:
            manifest = pl.read_parquet(
                product_root / f"swath/{batch}/{cruise}/extraction_manifest.parquet"
            ).select("cruise", "filekey", "source_relpath", "mb_format")
            for item in manifest.iter_rows(named=True):
                relpath = item["source_relpath"]
                source = raw_root / relpath
                inf_file = _inf_path(raw_root, relpath)
                inf = read_inf(inf_file, inf_file.as_posix()) if inf_file else {}
                scope = f"swath:{item['filekey']}"
                if item["mb_format"] == 41:
                    preamble = read_mb41_preamble(source, relpath)
                    row, texts, svp = _mb41_row(
                        relpath, item["filekey"], cruise, preamble, inf,
                    )
                    row["svp_id"] = register_svp(cruise, svp)
                    if preamble:
                        evidence.append({
                            "scope": scope,
                            "carrier": "mb41_gzip_preamble",
                            "location": f"{relpath}:bytes 0-{preamble.header_bytes}",
                            "text": "\n".join(texts),
                        })
                else:
                    row, texts = _binary_row(
                        cruise, item["filekey"], relpath, item["mb_format"], inf,
                    )
                    row["svp_id"] = None
                rows.append(row)
                if inf:
                    evidence.extend(_inf_evidence_rows(scope, inf))

    # HNRO14RR sample evidence (not part of the six-cruise product): kept
    # for the existing source depth/beam-anomaly sensitivity record.
    sample = raw_root / HNRO14RR_SAMPLE
    if sample.is_file():
        preamble = read_mb41_preamble(sample, HNRO14RR_SAMPLE)
        row, texts, svp = _mb41_row(
            HNRO14RR_SAMPLE, "hnro14rr_sample_20070726161003120", "HNRO14RR",
            preamble, {},
        )
        row["svp_id"] = register_svp("HNRO14RR", svp)
        row["is_sample_evidence_only"] = True
        evidence.append({
            "scope": "swath:hnro14rr_sample_20070726161003120",
            "carrier": "mb41_gzip_preamble",
            "location": f"{HNRO14RR_SAMPLE}:bytes 0-{preamble.header_bytes}",
            "text": "\n".join(texts),
        })
        rows.append(row)
    for row in rows:
        row.setdefault("is_sample_evidence_only", False)
        row.setdefault("svp_id", None)
    table = pl.DataFrame(rows, infer_schema_length=None)
    if svp_profiles:
        profile_table = pl.DataFrame(svp_profiles)
    else:
        profile_table = pl.DataFrame(
            schema={"svp_id": pl.Int64, "cruise": pl.String, "n_points": pl.Int64,
                    "profile_text": pl.String},
        )
    return table, profile_table, pl.DataFrame(evidence)


