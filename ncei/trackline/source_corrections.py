def _checks(product_root: Path, static_table: pl.DataFrame,
            legacy_table: pl.DataFrame, swath_table: pl.DataFrame,
            svp_table: pl.DataFrame, evidence: pl.DataFrame) -> dict:
    manifest = pl.read_parquet(product_root / "trackline/source_manifest.parquet")
    swath_manifest_keys = set()
    for batch, cruises in SWATH_BATCHES:
        for cruise in cruises:
            m = pl.read_parquet(
                product_root / f"swath/{batch}/{cruise}/extraction_manifest.parquet"
            )
            swath_manifest_keys.update(m["filekey"].to_list())
    product_rows = swath_table.filter(~pl.col("is_sample_evidence_only"))
    sample_rows = swath_table.filter(pl.col("is_sample_evidence_only"))

    mode_rows = swath_table.filter(pl.col("sound_speed_correction_state") == DEPTH_ADJUST_STATE)
    rr = swath_table.filter(pl.col("cruise") == "RR1412")
    rr_notice_evidence = evidence.filter(
        (pl.col("carrier") == "inf_file") & pl.col("scope").str.contains("RR1412|:filekey")
    )
    rr_notice_evidence = evidence.filter(
        (pl.col("carrier") == "inf_file")
        & pl.col("scope").is_in(
            [f"swath:{k}" for k in rr["filekey"].to_list()]
        )
    )
    hnro14 = swath_table.filter(pl.col("is_sample_evidence_only"))
    draft_static = static_table.filter(pl.col("draft_correction_state") == "declared_applied")
    draft_legacy = legacy_table.filter(pl.col("draft_correction_state") == "declared_applied")
    svp_counts = {
        cruise: count for cruise, count in svp_table.group_by("cruise").len()
        .iter_rows()
    }
    sample_svp_id = hnro14["svp_id"][0] if hnro14.height else None
    return {
        "command": "python -m ncei.trackline source-corrections",
        "coverage": {
            "trackline_rows": static_table.height,
            "trackline_unique_track_id": static_table["track_id"].n_unique(),
            "trackline_joins_source_manifest": static_table.height == manifest.height
            and set(static_table["track_id"].to_list()) == set(manifest["track_id"].to_list()),
            "legacy_rows": legacy_table.height,
            "legacy_own_header_rows": legacy_table.filter(
                ~pl.col("header_shared_with_static")).height,
            "legacy_additional_shared_rows": legacy_table.filter(
                pl.col("header_shared_with_static")).height,
            "swath_rows_total": swath_table.height,
            "swath_product_rows": product_rows.height,
            "swath_sample_rows": sample_rows.height,
            "swath_filekeys_match_manifests": (
                set(product_rows["filekey"].to_list()) == swath_manifest_keys
            ),
            "svp_profiles_per_cruise": svp_counts,
            "evidence_rows": evidence.height,
            "evidence_rows_by_carrier": {
                carrier: count for carrier, count in
                evidence.group_by("carrier").len().iter_rows()
            },
        },
        "cases": {
            "hnro06rr_transducer_depth_heave_mode": {
                "files": mode_rows.height,
                "cruises": sorted(set(mode_rows["cruise"].to_list())),
                "state": DEPTH_ADJUST_STATE,
                "all_modes_quote_transducer_depth_and_or_heave": mode_rows[
                    "mbprocess_mode_statement"
                ].str.contains("transducer depth and/or heave").all(),
                "all_heave_step_verbatim_not_modified": (
                    mode_rows["heave_step_state"]
                    .str.replace(" +", " ", literal=False)
                    .str.to_lowercase() == "heave: not modified"
                ).all() if mode_rows.height else None,
                "all_draft_set_6m": mode_rows["draft_step"].str.contains("6.000000").all()
                if mode_rows.height else None,
                "example_relpath": mode_rows["source_relpath"][0] if mode_rows.height else None,
                "example_mode_statement": mode_rows["mbprocess_mode_statement"][0]
                if mode_rows.height else None,
            },
            "rr1412_inf_notices": {
                "rows": rr.height,
                "rows_with_inf_path": rr.filter(pl.col("inf_path").is_not_null()).height,
                "rows_with_svp_notice": rr.filter(pl.col("inf_svp_notice").is_not_null()).height,
                "rows_with_ssv_notice": rr.filter(pl.col("inf_ssv_notice").is_not_null()).height,
                "rows_with_attitude_notice": rr.filter(
                    pl.col("inf_attitude_notice").is_not_null()).height,
                "evidence_notice_rows": rr_notice_evidence.height,
                "example_svp_notice": rr.filter(pl.col("inf_svp_notice").is_not_null())[
                    "inf_svp_notice"][0],
                "example_svp_notice_location": (
                    rr.filter(pl.col("inf_svp_notice").is_not_null())["inf_path"][0]
                    + ":line "
                    + str(rr.filter(pl.col("inf_svp_notice").is_not_null())[
                        "inf_svp_notice_line"][0])
                ),
            },
            "hnro14rr_sample": {
                "rows": hnro14.height,
                "is_sample_evidence_only": bool(hnro14["is_sample_evidence_only"].all()),
                "svp_id": sample_svp_id,
                "svp_id_in_profile_table": (
                    sample_svp_id in svp_table["svp_id"].to_list()
                    if sample_svp_id is not None else False
                ),
                "svp_n_points": hnro14["svp_n_points"][0] if hnro14.height else None,
                "state": hnro14["sound_speed_correction_state"][0] if hnro14.height else None,
            },
            "mgd77t_draft_tide_attitude": {
                "static_declared_applied": {
                    r["track_id"]: r["draft_correction_value_m"]
                    for r in draft_static.iter_rows(named=True)
                },
                "legacy_declared_applied": {
                    r["track_id"]: r["draft_correction_value_m"]
                    for r in draft_legacy.iter_rows(named=True)
                },
                "static_tide_unknown_rows": static_table.filter(
                    pl.col("tide_correction_state") == "unknown").height,
                "static_attitude_unknown_rows": static_table.filter(
                    pl.col("attitude_correction_state") == "unknown").height,
                "legacy_tide_unknown_rows": legacy_table.filter(
                    pl.col("tide_correction_state") == "unknown").height,
            },
        },
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m ncei.trackline source-corrections",
        description=__doc__.splitlines()[0],
    )
    parser.add_argument(
        "--product-root", type=Path,
        default=Path("ncei/derived/processing_revision_20261025"),
    )
    parser.add_argument(
        "--raw-root", type=Path, default=Path("ncei/raw_round2/platforms_tree"),
    )
    parser.add_argument("--output-name", default="source_corrections")
    args = parser.parse_args(argv)

    product_root = args.product_root
    raw_root = args.raw_root
    out = product_root / args.output_name
    out.mkdir(parents=True, exist_ok=True)

    static_table, static_evidence, _ = build_trackline_tables(product_root)
    static_table.write_parquet(out / "trackline_source_corrections.parquet")
    static_table.write_csv(out / "trackline_source_corrections.csv")
    static_table.select(
        "track_id", "sound_velocity_assumed_header", "sound_speed_correction_state",
        "vertical_datum_state", "draft_correction_state", "draft_correction_value_m",
        "tide_correction_state", "attitude_correction_state",
        "gravity_formula_code", "gravity_formula_text",
        "gravity_reference_system_code", "gravity_reference_system_text",
        "gravity_corrections_text", "bat_cpco_coded_records",
    ).write_csv(out / "trackline_correction_summary.csv")

    legacy_table = build_legacy_faa_table(product_root, static_table)
    legacy_table.write_parquet(out / "legacy_faa_source_corrections.parquet")
    legacy_table.write_csv(out / "legacy_faa_source_corrections.csv")

    swath_table, svp_table, swath_evidence = build_swath_tables(product_root, raw_root)
    swath_table.write_parquet(out / "swath_source_corrections.parquet")
    swath_table.write_csv(out / "swath_source_corrections.csv")
    svp_table.write_parquet(out / "swath_svp_profiles.parquet")

    evidence = pl.concat([static_evidence, swath_evidence], how="diagonal")
    evidence.write_parquet(out / "evidence_texts.parquet")

    summary = []
    for sub in swath_table.partition_by("cruise", as_dict=False):
        cruise = sub["cruise"][0]
        summary.append({
            "table": "swath", "cruise": cruise,
            "files": sub.height,
            "sound_speed_applied_raytrace": sub.filter(
                pl.col("sound_speed_correction_state") == RAYTRACE_STATE
            ).height,
            "sound_speed_declared_depth_adjustment_mode": sub.filter(
                pl.col("sound_speed_correction_state") == DEPTH_ADJUST_STATE
            ).height,
            "svp_records_present_unknown": sub.filter(
                pl.col("sound_speed_correction_state") == "svp_records_present_application_unknown"
            ).height,
            "sound_speed_unknown": sub.filter(
                pl.col("sound_speed_correction_state") == "unknown"
            ).height,
            "tide_not_applied_in_step": sub.filter(
                pl.col("tide_state") == "not_applied_in_this_step"
            ).height,
            "bias_reapplication_off": sub.filter(
                pl.col("attitude_bias_step_state") == "bias_reapplication_off_in_this_step"
            ).height,
        })
    summary_rows = [{k: (json.dumps(v, sort_keys=True) if isinstance(v, dict) else v)
                     for k, v in item.items()} for item in summary]
    pl.DataFrame(summary_rows).sort("cruise").write_csv(out / "summary.csv")

    checks = _checks(product_root, static_table, legacy_table, swath_table,
                     svp_table, evidence)
    (out / "checks.json").write_text(
        json.dumps(checks, indent=2, sort_keys=True) + "\n", encoding="utf-8",
    )
    print(f"wrote {out}")
    return 0
