def _header_state_rows(track_id: str, fields: dict[str, str], source_kind: str,
                       evidence_file: str, survey_id_mismatch: bool = False) -> dict:
    sound_vel = fields.get("SOUND_VEL", "").strip()
    vdatum = fields.get("VDATUM_CO", "").strip()
    add_doc = fields.get("ADD_DOC", "").strip()
    draft_value = _DRAFT_VALUE_RE.search(add_doc) if add_doc else None
    draught_declared = _DRAUGHT_RE.search(add_doc) if add_doc else None
    return {
        "source_kind": source_kind,
        "track_id": track_id,
        "header_survey_id_mismatch": survey_id_mismatch,
        # Sound speed: header SOUND_VEL is the assumed velocity used by the
        # recorder, not proof that a correction was applied.
        "sound_velocity_assumed_header": sound_vel or None,
        "sound_velocity_unit": "m/s" if sound_vel else None,
        "sound_speed_correction_state": (
            "assumed_velocity_declared" if sound_vel else "unknown"
        ),
        "sound_speed_correction_evidence": (
            "header SOUND_VEL" if sound_vel else "no header declaration"
        ),
        # Vertical datum
        "vertical_datum_state": (
            f"declared:{_vdatum_label(vdatum)}" if vdatum else "unknown"
        ),
        "vertical_datum_code": vdatum or None,
        "vertical_datum_evidence": "header VDATUM_CO" if vdatum else "no header declaration",
        # Draft: only an explicit declaration in ADD_DOC establishes a state.
        "draft_correction_state": (
            "declared_applied" if (draft_value or draught_declared) else "unknown"
        ),
        "draft_correction_value_m": (
            float(draft_value.group(1)) if draft_value else None
        ),
        "draft_correction_evidence": (
            "header ADD_DOC: "
            + (draft_value.group(0) if draft_value else draught_declared.group(0))
            if (draft_value or draught_declared) else "no header declaration"
        ),
        # Tide and attitude have no formal MGD77T header field.
        "tide_correction_state": "unknown",
        "tide_correction_evidence": "no header field in MGD77T formal header",
        "attitude_correction_state": "unknown",
        "attitude_correction_evidence": "no header field in MGD77T formal header",
        # Interpolation
        "bathymetry_interpolation_scheme": fields.get("BATH_INTRP", "").strip() or None,
        # Instrument (descriptive only, never a correction proof)
        "bathymetry_instrument": fields.get("BATH_INSTR", "").strip() or None,
        "bathymetry_additional_forms": fields.get("BATH_ADD", "").strip() or None,
        # Gravity declarations, verbatim retained
        "gravity_formula_code": fields.get("G_FORMU_CO", "").strip() or None,
        "gravity_formula_code_label": _g_formu_label(fields.get("G_FORMU_CO", "")),
        "gravity_formula_text": fields.get("GRAV_FORMU", "").strip() or None,
        "gravity_reference_system_code": fields.get("G_RFSYS_CO", "").strip() or None,
        "gravity_reference_system_code_label": _g_rfsys_label(fields.get("G_RFSYS_CO", "")),
        "gravity_reference_system_text": fields.get("GRAV_RFSYS", "").strip() or None,
        "gravity_corrections_text": fields.get("GRAV_CORR", "").strip() or None,
        "additional_documentation": add_doc or None,
        "header_evidence_file": evidence_file,
    }


def build_trackline_tables(product_root: Path) -> tuple[pl.DataFrame, pl.DataFrame, pl.DataFrame]:
    """One row per static source (695) plus per-record BAT_CPCO summaries."""
    headers = pl.read_parquet(product_root / "trackline/source_headers.parquet")
    manifest = pl.read_parquet(product_root / "trackline/source_manifest.parquet")
    mismatch = {
        row["track_id"]: bool(row["source_header_survey_id_mismatch"])
        for row in manifest.select("track_id", "source_header_survey_id_mismatch").iter_rows(named=True)
    }
    instrument = {
        row["track_id"]: row["instrument_class_pred"]
        for row in manifest.select("track_id", "instrument_class_pred").iter_rows(named=True)
    }

    rows = []
    evidence = []
    for row in headers.iter_rows(named=True):
        track_id = row["track_id"]
        state = _header_state_rows(
            track_id, row, "static_mgd77t_header",
            row["source_header_file"], mismatch.get(track_id, False),
        )
        state["instrument_class_pred"] = instrument.get(track_id)
        rows.append(state)
        for field in STATIC_FIELDS:
            value = (row.get(field) or "").strip()
            if value:
                evidence.append({
                    "scope": f"static:{track_id}", "carrier": "formal_header",
                    "location": f"{row['source_header_file']}:{field}",
                    "text": value,
                })
    table = pl.DataFrame(rows)

    # Per-record BAT_CPCO frequencies at source scope (all original records).
    counts = pl.read_csv(product_root / "trackline/source_quality_counts.csv")
    cpco = counts.filter(
        (pl.col("field") == "BAT_CPCO") & (pl.col("selection") == "source")
    )
    cpco_map: dict[str, dict[str, int]] = {}
    for row in cpco.iter_rows(named=True):
        cpco_map.setdefault(row["track_id"], {})[
            "unspecified" if row["code"] is None else str(row["code"])
        ] = row["count"]
    coded = []
    for track_id, dist in cpco_map.items():
        unspecified = dist.get("unspecified", 0)
        specified = {k: v for k, v in dist.items() if k != "unspecified"}
        coded.append({
            "track_id": track_id,
            "bat_cpco_coded_records": sum(specified.values()),
            "bat_cpco_unspecified_records": unspecified,
            "bat_cpco_coded_distribution": json.dumps(specified, sort_keys=True),
            "bat_cpco_coded_labels": json.dumps(
                {k: _bat_cpco_label(k) for k in sorted(specified)}, sort_keys=True,
            ),
        })
    coded_df = pl.DataFrame(coded) if coded else pl.DataFrame(
        schema={"track_id": pl.String, "bat_cpco_coded_records": pl.Int64,
                "bat_cpco_unspecified_records": pl.Int64,
                "bat_cpco_coded_distribution": pl.String,
                "bat_cpco_coded_labels": pl.String},
    )
    table = table.join(coded_df, on="track_id", how="left")
    return table, pl.DataFrame(evidence), coded_df


def build_legacy_faa_table(product_root: Path, static_table: pl.DataFrame) -> pl.DataFrame:
    """21 rows: 15 surveys with their own headers; 6 additional surveys
    linked to their static-tree header row (no double counting)."""
    from ncei.trackline.mgd77t import read_header

    meta_dir = product_root / "legacy_faa/source_metadata"
    manifest = pl.read_csv(product_root / "legacy_faa/conversion_manifest.csv")
    rows = []
    for row in manifest.iter_rows(named=True):
        cruise = row["cruise_id"]
        header_path = meta_dir / f"{cruise}.h77t"
        header = read_header(header_path, cruise)
        fields = header.fields
        state = _header_state_rows(cruise, fields, "legacy_faa_header", str(header_path))
        state.update({
            "source_observations": row["source_rows"],
            "faa_finite": row["faa_finite"],
            "additional_static_track_id": None,
            "header_shared_with_static": False,
        })
        rows.append(state)
    additional = pl.read_csv(product_root / "legacy_faa_additional/source_inventory.csv")
    static_by_id = {
        r["track_id"]: r for r in static_table.iter_rows(named=True)
    }
    for row in additional.iter_rows(named=True):
        cruise = row["cruise_id"]
        static = dict(static_by_id[cruise])
        static.pop("source_kind", None)
        state = _header_state_rows(
            cruise, {}, "legacy_faa_additional", row["formal_header"],
        )
        # copy header-derived states from the static row (same formal header)
        for key, value in static.items():
            if (key.startswith(("sound_", "vertical_", "bathymetry_", "gravity_",
                                "additional_", "draft_", "tide_", "attitude_"))
                    or key in ("header_evidence_file", "instrument_class_pred",
                               "bat_cpco_coded_records", "bat_cpco_unspecified_records",
                               "bat_cpco_coded_distribution", "bat_cpco_coded_labels")):
                state[key] = value
        state.update({
            "source_observations": row["source_observations"],
            "faa_finite": None,
            "additional_static_track_id": cruise,
            "header_shared_with_static": True,
        })
        rows.append(state)
    table = pl.DataFrame(rows)

    counts = pl.read_csv(product_root / "legacy_faa/source_code_counts.csv")
    cpco = counts.filter(pl.col("field") == "BAT_CPCO")
    cpco_map = {}
    for row in cpco.iter_rows(named=True):
        cpco_map.setdefault(row["cruise_id"], {})[
            "unspecified" if not row["source_code"] else row["source_code"]
        ] = row["observations"]
    counts2 = pl.read_csv(product_root / "legacy_faa_additional/source_code_counts.csv")
    for row in counts2.filter(pl.col("field") == "BAT_CPCO").iter_rows(named=True):
        cpco_map.setdefault(row["cruise_id"], {})["unspecified"] = row["observations"]
    coded = []
    for cruise, dist in cpco_map.items():
        unspecified = dist.get("unspecified", 0)
        specified = {k: v for k, v in dist.items() if k != "unspecified"}
        coded.append({
            "track_id": cruise,
            "bat_cpco_coded_records": sum(specified.values()),
            "bat_cpco_unspecified_records": unspecified,
            "bat_cpco_coded_distribution": json.dumps(specified, sort_keys=True),
            "bat_cpco_coded_labels": json.dumps(
                {k: _bat_cpco_label(k) for k in sorted(specified)}, sort_keys=True),
        })
    coded_df = pl.DataFrame(coded)
    table = table.drop([
        c for c in ("bat_cpco_coded_records", "bat_cpco_unspecified_records",
                    "bat_cpco_coded_distribution", "bat_cpco_coded_labels")
        if c in table.columns
    ]).join(coded_df, on="track_id", how="left")
    return table


